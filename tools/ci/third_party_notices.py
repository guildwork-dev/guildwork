"""Generate THIRD_PARTY_NOTICES (architecture 12 section 2.3, 06 section 8).

The file lists what Guildwork ships from third parties: every runtime
dependency (npm and Python, from license_inventory.py) with name, version,
SPDX expression and the copyright lines of its license files (the author of
the package if no file has one), and every adopted file with its license,
copyright holders and Origin line. Development dependencies are not shipped
and not listed. The license texts are in LICENSES/<id>.txt.

  --write  write THIRD_PARTY_NOTICES (make notices)
  --check  compare the file with the generated text (part of make licenses)

Standard library only (FE-004).

Exit codes:
  0  written, or the file is up to date
  1  the file is missing or outdated: `THIRD_PARTY_NOTICES:1:1 notices-outdated`
  2  pnpm, uv.lock or the Python environment unreadable:
     `notices.inventory_failed path=<path> reason=<reason>` on stderr
"""

from __future__ import annotations

import argparse
import re
import sys
from collections.abc import Sequence
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if not __package__:
    # Run as a script (make notices): make the tools package importable.
    sys.path.insert(0, str(REPO_ROOT))

from tools.ci.license_inventory import (  # noqa: E402
    Dependency,
    InventoryError,
    adopted_files,
    collect_dependencies,
    tracked_files,
)

EXIT_OK = 0
EXIT_OUTDATED = 1
EXIT_CONFIG = 2

NOTICES_PATH = "THIRD_PARTY_NOTICES"
COPYRIGHT_LINE = re.compile(r"^\s*(?:Copyright\b|\(c\)\s|\u00a9)", re.IGNORECASE)
FORBIDDEN_DASHES = re.compile("[\u2012-\u2015]")

INTRO = """\
Third party notices of Guildwork

This file lists the third party components that Guildwork ships and the
files it adopted from other projects, with their licenses and copyright
notices. It is generated by tools/ci/third_party_notices.py from the
lockfiles, the installed packages and the headers of adopted files; do not
edit it by hand, run `make notices`. The license texts are in
LICENSES/<SPDX identifier>.txt. Development tools are not shipped and not
listed here.
"""


def _clean(line: str) -> str:
    # Third party texts may contain dashes the repository does not allow (FE-022).
    return FORBIDDEN_DASHES.sub("-", " ".join(line.split()))


def copyright_lines(dep: Dependency) -> list[str]:
    """Copyright lines of the license files of dep, in file order, without duplicates."""
    lines: list[str] = []
    for name in dep.license_files:
        try:
            text = Path(name).read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for line in text.splitlines():
            if COPYRIGHT_LINE.match(line):
                cleaned = _clean(line)
                if cleaned not in lines:
                    lines.append(cleaned)
    return lines


def render(root: Path, deps: Sequence[Dependency]) -> str:
    """The text of THIRD_PARTY_NOTICES for the repository at root and deps."""
    out = [INTRO.rstrip("\n"), "", "Runtime dependencies", ""]
    runtime = sorted((d for d in deps if d.runtime), key=lambda d: (d.ecosystem, d.name, d.version))
    if not runtime:
        out += ["None.", ""]
    for dep in runtime:
        out.append(f"{dep.ecosystem} {dep.name} {dep.version}")
        out.append(f"  License: {dep.license or 'not declared'}")
        copyrights = copyright_lines(dep)
        if copyrights:
            out += [f"  {line}" for line in copyrights]
        elif dep.author:
            out.append(f"  Author: {_clean(dep.author)}")
        out.append("")
    out += ["Adopted files", ""]
    adopted = adopted_files(root, tracked_files(root))
    if not adopted:
        out += ["None.", ""]
    for part in adopted:
        out.append(part.path)
        out.append(f"  License: {part.license}")
        out += [f"  Copyright: {_clean(holder)}" for holder in part.copyrights]
        out.append(f"  Origin: {part.origin}")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def write(root: Path, deps: Sequence[Dependency]) -> None:
    (root / NOTICES_PATH).write_text(render(root, deps), encoding="utf-8")


def check(root: Path, deps: Sequence[Dependency]) -> list[str]:
    """Findings: one if THIRD_PARTY_NOTICES is missing or differs from render()."""
    try:
        current = (root / NOTICES_PATH).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        current = None
    if current == render(root, deps):
        return []
    state = "is missing" if current is None else "is outdated"
    return [f"{NOTICES_PATH}:1:1 notices-outdated {NOTICES_PATH} {state}; run make notices"]


def parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate or check THIRD_PARTY_NOTICES.")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="repository root")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="write the file")
    mode.add_argument("--check", action="store_true", help="fail if the file is outdated")
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        deps = collect_dependencies(args.root)
        if args.write:
            write(args.root, deps)
            return EXIT_OK
        findings = check(args.root, deps)
    except InventoryError as exc:
        print(f"notices.inventory_failed path={exc.path} reason={exc}", file=sys.stderr)
        return EXIT_CONFIG
    for finding in findings:
        print(finding)
    return EXIT_OUTDATED if findings else EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
